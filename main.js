  /* ---------- effect 指令解析（提示词包第五节） ----------
     trust+2 / renown+1　数值自增，钳制 0—10
     silver=taken　　　  枚举赋值
     items+=三块银元　　  物品入栏（去重）
     mementos+=…　　　   纪念物（结算层用，本原型不展示）
     route= / branch=　  仅 E、H 两个真分叉节点写入，A—D 不出现
     返回本次新入栏的物品，供「飞入状态栏」动画使用 */
  function applyEffect(str) {
    var added = [];
    if (!str) return added;

    str.split(';').forEach(function (raw) {
      var part = raw.replace(/^\s+|\s+$/g, '');
      if (!part) return;
      var m;

      if ((m = part.match(/^(trust|renown)([+-])(\d+)$/))) {
        var d = (m[2] === '+' ? 1 : -1) * parseInt(m[3], 10);
        state.flags[m[1]] = clamp10(state.flags[m[1]] + d);
      } else if ((m = part.match(/^items\+=(.+)$/))) {
        var item = m[1].replace(/^\s+|\s+$/g, '');
        if (item && state.items.indexOf(item) < 0) { state.items.push(item); added.push(item); }
      } else if ((m = part.match(/^mementos\+=(.+)$/))) {
        var mem = m[1].replace(/^\s+|\s+$/g, '');
        if (mem && state.mementos.indexOf(mem) < 0) state.mementos.push(mem);
      } else if ((m = part.match(/^([a-z_]+)=([A-Za-z_]+)$/))) {
        var v = m[2];
        state.flags[m[1]] = (v === 'true') ? true : (v === 'false' ? false : v);
      } else if (part === 'NODE_SPARK') {
        state.flags.heard_spark = true;
      }
    });

    console.log('[effect] ' + str + '\n  flags =', JSON.parse(JSON.stringify(state.flags)),
                '\n  items =', state.items.slice());
    return added;
  }

