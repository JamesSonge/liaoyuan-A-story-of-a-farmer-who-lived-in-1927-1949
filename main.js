  /* 播放一组句子，播完调 done() */
  function play(lines, done, opts) {
    state.script = { lines: lines, i: 0, done: done, opts: opts || {} };
    state.phase = 'dialogue';
    renderLine(0);
  }

  function renderLine(idx) {
    var s = state.script, line = s.lines[idx];
    if (line.node === 'NODE_SPARK') recordSpark();

    var box = $('dialog-box'), text = $('dialog-text'),
        speaker = $('speaker'), prog = $('line-progress');

    prog.textContent = s.opts.progress ? (idx + 1) + ' / ' + s.lines.length : '';

    function paint() {
      speaker.textContent = line.speaker || '旁白';
      text.textContent = line.text;
      box.classList.remove('is-leaving');
      box.classList.remove('is-entering');
      void box.offsetWidth;                 /* 强制回流，动画重新触发 */
      box.classList.add('is-entering');
      window.setTimeout(function () { box.classList.remove('is-entering'); }, T.boxIn + 30);
    }

    if (!text.textContent) { paint(); return; }   /* 首句直接飞入 */

    box.classList.add('is-leaving');
    lock(T.lineOut + T.boxIn);
    window.setTimeout(paint, T.lineOut);
  }

  function advance() {
    if (state.busy) return;
    if (state.phase !== 'dialogue' || !state.script) return;
    var s = state.script;
    if (s.i + 1 < s.lines.length) { s.i++; renderLine(s.i); return; }
    var done = s.done;
    state.script = null;
    if (done) done();
  }

  /* 节点对白 = 固定 dialogue ＋（若有）按状态挑中的那一句。
     只有 F-1 用得上：silver=taken / refused / neither 三句里只播一句。 */
  function nodeDialogue(node) {
    var lines = node.dialogue.slice();
    if (node.stateText) {
      var key = 'silver=' + (state.flags.silver === null ? '' : state.flags.silver);
      var extra = node.stateText[key];
      if (extra) {
        lines.push({ speaker: '旁白', text: extra });
        console.log('[状态变体] ' + node.id + ' 采用 ' + key + ' 那一句');
      }
    }
    return lines;
  }

  function playNode(index) {
    var chapter = CHAPTERS[state.chapterId];
    var node = chapter.nodes[index];
    state.nodeIndex = index;
    if (state.visited.indexOf(node.id) < 0) state.visited.push(node.id);
    $('node-label').textContent = node.id + ' · ' + node.label;
    $('stage').classList.add('is-locked');
    setHint(node.isBranch ? '★ 路线分叉 —— 这一选决定后面走哪条线'
                          : '点击画面 / 空格　推进');

    play(nodeDialogue(node), function () {
      if (node.choices && node.choices.length) showChoices(node);
      else finishNode(index);
    }, { progress: true });
  }

  function finishNode(index) {
    var chapter = CHAPTERS[state.chapterId];
    if (index + 1 < chapter.nodes.length) { playNode(index + 1); return; }
    playCoda();
  }

